from FlagEmbedding import BGEM3FlagModel

# 모델 로드 (이미 클래스 내부에 선언하셨으니 해당 인스턴스의 tokenizer를 쓰셔도 됩니다)
model = BGEM3FlagModel('BAAI/bge-m3', use_fp16=True)
tokenizer = model.tokenizer

text = """결론부터 말씀드리면, API 비용으로 청구되는 토큰은 **"사용자가 보낸 텍스트(Input) + LLM이 생성한 텍스트(Output)"**가 주를 이룹니다. 하지만 내부적으로 추가되는 **'숨은 토큰'**들도 분명히 존재하며, 이를 이해해야 예상치 못한 과금을 방지할 수 있습니다.

상세한 구성 요소는 다음과 같습니다.

1. 사용자가 직접 보낸 토큰 (Input Tokens)
가장 기본이 되는 부분으로, 프롬프트에 포함된 모든 텍스트가 해당됩니다.

프롬프트 본문: 질문이나 명령.

대화 이력 (Context): 이전 대화 내용을 함께 보낸다면 그 양만큼 매번 비용이 발생합니다. (이게 쌓이면 꽤 커집니다.)

2. 시스템 및 구조적 토큰 (Hidden/Metadata Tokens)
사용자가 직접 타이핑하지 않았지만, API를 호출할 때 서버가 자동으로 붙이거나 구조적으로 필요한 토큰들입니다.

System Message: "너는 유능한 개발자야" 같은 역할 부여 설정값.

Role Identifiers: User:, Assistant: 같은 대화의 화자를 구분하기 위한 특수 구분자(Special Tokens).

이미지/파일 토큰: 이미지를 보낼 때, 픽셀 데이터가 토큰으로 변환됩니다. (예: GPT-4o는 이미지 한 장당 크기에 따라 약 85~170개 이상의 토큰을 소모합니다.)

3. 모델이 생성한 토큰 (Output Tokens)
LLM이 답변으로 출력하는 모든 텍스트입니다.

주의사항: 출력 단가가 입력 단가보다 보통 3~5배 정도 비쌉니다. 따라서 답변이 길어질수록 비용이 급격히 상승합니다.

4. 내부적으로 더 고려해야 할 요소 (Advanced)
단순히 글자 수 = 토큰 수가 아닌, 비용에 영향을 주는 추가 요소들은 다음과 같습니다.

함수 호출 (Function Calling): 외부 툴(날씨 확인, DB 조회 등)을 사용하도록 설정하면, 모델이 해당 함수를 쓰기 위해 내부적으로 생성하는 JSON 형식의 텍스트도 모두 토큰으로 계산됩니다.

생각의 연쇄 (Reasoning Tokens): OpenAI의 o1 모델 같은 추론 전용 모델은 답변을 내기 전 내부적으로 "생각(Thinking)"을 합니다. 사용자의 눈에는 보이지 않지만, 이 '속마음' 과정에서 소모된 토큰도 모두 출력 토큰 비용으로 청구됩니다.

프롬프트 캐싱 (Prompt Caching): 반대로 비용을 아껴주는 요소입니다. 똑같은 지시사항이나 긴 문서를 반복해서 보내면, 모델이 이를 기억(캐싱)하여 입력 비용을 50~90%까지 깎아주기도 합니다.

💡 요약
비용 계산 시에는 다음 공식으로 접근하는 것이 가장 정확합니다.

총 청구 토큰 = (시스템 설정 + 대화 이력 + 현재 질문) + (모델의 추론 과정 + 최종 답변)

만약 대규모 서비스를 기획 중이시라면, **"대화 이력(History)"**이 누적됨에 따라 입력 토큰이 기하급수적으로 늘어나는 점을 가장 경계해야 합니다. 이를 최적화하기 위해 이전 대화를 요약해서 보내는 등의 기술이 필요합니다.

혹시 특정 모델(예: o1 추론 모델)을 염두에 두고 계신가요? 그 모델의 특수한 토큰 계산 방식을 더 자세히 설명해 드릴 수 있습니다."""

# 1. 토큰화 (텍스트 -> 토큰 ID)
tokens = tokenizer.encode(text, add_special_tokens=True)

# 2. 토큰 ID를 다시 읽을 수 있는 단어 조각으로 변환
token_pieces = [tokenizer.decode([t]) for t in tokens]

print(f"원문: {text}")
print("-" * 30)
print(f"토큰 ID 리스트: {tokens}")
print(f"토큰 조각 매칭: {token_pieces}")
print(f"토큰 개수: {len(tokens)}")